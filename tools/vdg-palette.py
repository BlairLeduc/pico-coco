#!/usr/bin/env python3
"""vdg-palette.py — the colours an NTSC set shows from a CoCo's MC6847 and
MC1372, as mc6847.c's tables (design.md §9.5).

    tools/vdg-palette.py            # the C tables, for src/core/mc6847.c

The model, each step from a primary source:

  - The VDG's outputs for each colour: luminance Y and the colour
    differences phiB and phiA, the MC6847 datasheet's typical levels
    (figure 10); the text screen's orange is graphics orange's chroma at
    white's luminance.
  - The MC1372 (Motorola's datasheet): two modulators with equal gain,
    B leading A by 100 degrees (85 to 115); B is (B-Y), since the burst
    is phiB 0.25 V below the 1.5 V reference, and A approximates (R-Y).
  - The set's colour control holds the burst at 20 IRE (the NTSC
    standard), so a colour difference of 0.25 V is 20 IRE of chroma,
    whatever the board's chroma level; luminance has blanking (0.77 V)
    at 0 IRE and the VDG's white (0.42 V) at 100.
  - The set demodulates on axes 90 degrees apart and decodes with NTSC's
    weights: U = 0.492 (B-Y), V = 0.877 (R-Y), and G-Y from Y's.
  - Shown with the VDG's black (0.72 V, 14.3 IRE) as black and white at
    WHITE IRE, the set's contrast: each channel clipped, as a CRT's
    guns saturate. Above 100, colours brighter than white keep their hue.

test_mc6847 derives the same tables in C. Nothing here is XRoar's or
MAME's code; MAME's capture of a PAL Dragon, with its 90-degree LM1889,
is what the model was held to (design.md §9.5).
"""

import math

PHI_A_LAG = 100.0            # MC1372: B leads A by 100 degrees
BURST_V = 0.25               # phiB's burst below the reference, volts
BURST_IRE = 20.0             # NTSC burst amplitude
BLANK_V, WHITE_V, BLACK_V = 0.77, 0.42, 0.72
WHITES = (100, 115, 130)     # the candidates for the set's white, IRE

# The datasheet's typical Y, phiB, phiA (volts), in mc6847.h's order.
COLOURS = [
    ("VDG_GREEN",         0.54, 1.0, 1.0),
    ("VDG_YELLOW",        0.42, 1.0, 1.5),
    ("VDG_BLUE",          0.65, 2.0, 1.5),
    ("VDG_RED",           0.65, 1.5, 2.0),
    ("VDG_BUFF",          0.42, 1.5, 1.5),
    ("VDG_CYAN",          0.54, 1.5, 1.0),
    ("VDG_MAGENTA",       0.54, 2.0, 2.0),
    ("VDG_ORANGE",        0.54, 1.0, 2.0),
    ("VDG_BLACK",         0.72, 1.5, 1.5),
    ("VDG_DARK_GREEN",    0.72, 1.0, 1.0),
    ("VDG_DARK_ORANGE",   0.72, 1.0, 2.0),
    ("VDG_BRIGHT_ORANGE", 0.42, 1.0, 2.0),
]


def rgb(y, phb, pha, white):
    lum = (BLANK_V - y) / (BLANK_V - WHITE_V) * 100.0
    k = BURST_IRE / BURST_V
    cb, ca = k * (phb - 1.5), k * (pha - 1.5)
    t = math.radians(PHI_A_LAG)
    u = cb + ca * math.cos(t)
    v = ca * math.sin(t)
    by, ry = u / 0.492, v / 0.877
    gy = -(0.299 / 0.587) * ry - (0.114 / 0.587) * by
    black = (BLANK_V - BLACK_V) / (BLANK_V - WHITE_V) * 100.0
    out = []
    for c in (lum + ry, lum + gy, lum + by):
        x = (c - black) / (white - black)
        out.append(int(math.floor(min(1.0, max(0.0, x)) * 255.0 + 0.5)))
    return out


def main():
    print("/* Generated by tools/vdg-palette.py (design.md §9.5). */")
    for w in WHITES:
        print(f"    [MC6847_TV{w}] = {{")
        for name, y, b, a in COLOURS:
            r, g, bl = rgb(y, b, a, w)
            print(f"        [{name}]".ljust(30) + f"= RGB565(0x{r:02X}, 0x{g:02X}, 0x{bl:02X}),")
        print("        [VDG_ARTEFACT_BLUE]   = RGB565(0x00, 0x80, 0xFF),")
        print("        [VDG_ARTEFACT_RED]    = RGB565(0xFF, 0x80, 0x00),")
        print("    },")


if __name__ == "__main__":
    main()
