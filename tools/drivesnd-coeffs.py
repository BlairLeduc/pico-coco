#!/usr/bin/env python3
"""drivesnd-coeffs.py — the synthesised drive's coefficients, from what
was measured in recordings of a drive (design.md §10, drivesnd.c).

Writes src/core/drivesnd_coeffs.h. The figures below were measured on
2026-11-22 from three recordings of a 3.5-inch drive reading (the
owner's, from Pixabay, not in the tree), 39 steps and 564 windows of
the drive's noise between them:

  the noise   a hump at 1 kHz: 300 Hz -6 dB, 600 -4, 1.3 kHz -3, 2 kHz
              -9, 4 kHz -15, 8 kHz -25; RMS about 440; no sway once a
              revolution, but swells of 50 to 100 ms; tones at 983 Hz,
              rms 79, and 3,995 Hz, rms 27 (a 54 Hz hum, mains or
              below the speaker, left out)
  a step      peaks in its excess over the noise at 590, 733, 1,234,
              1,556, 2,217, 2,503, 2,986, 5,060 and 7,725 Hz; RMS over
              the noise about 1,100 for its first 3 ms, half of that by
              6 ms, a second rise at 9 ms (the head settling), then a
              tail of the noise's own colour some 5 dB up, gone by 45 ms

  tools/drivesnd-coeffs.py > src/core/drivesnd_coeffs.h
"""

import math

FS = 150e6 / 4096   # the PCM's nominal rate

# A step's modes: frequency, decay time constant in ms, amplitude
# (relative). Decays shorten with frequency, as a struck plate's do,
# fitted to the excess's fall: 1,100 to 550 in about 3 ms.
MODES = [
    (590, 9.0, 0.60),
    (733, 9.0, 0.60),
    (1234, 7.0, 1.00),
    (1556, 6.0, 1.20),
    (2217, 5.0, 1.00),
    (2503, 5.0, 0.90),
    (2986, 4.0, 0.90),
    (5060, 2.5, 0.70),
    (7725, 1.5, 0.60),
]

# The noise's hump, fitted to the bands above by least squares
# (2026-11-22): a two-pole resonance at 1,050 Hz, Q 1.4, fed through a
# zero at 0.9, which slopes its low side as gently as the drive's, and a
# one-pole low pass at 6 kHz after it; within 2.3 dB of every band from
# 200 Hz to 8 kHz, 3.6 dB over at 10 kHz.
HUMP_F, HUMP_Q, HUMP_ZERO, HUMP_LP = 1050.0, 1.4, 0.9, 6000.0
TONES = [(983.0, 79.0), (3995.0, 27.0)]    # Hz, RMS at a noise of 440


def resonator(f, tau_ms):
    r = math.exp(-1.0 / (tau_ms * 1e-3 * FS))
    w = 2 * math.pi * f / FS
    return 2 * r * math.cos(w), r * r, math.sin(w)


def q14(v):
    return int(round(v * 16384))


def main():
    print("/* drivesnd_coeffs.h — generated by tools/drivesnd-coeffs.py, from")
    print(" * measurements of a drive's recordings (that script). Do not edit. */")
    print("#ifndef PICO_COCO_DRIVESND_COEFFS_H")
    print("#define PICO_COCO_DRIVESND_COEFFS_H")
    print()
    print("#include <stdint.h>")
    print()
    print("/* A step's modes: c1 = 2 r cos w and c2 = r^2 in Q14, and the strike")
    print(" * into y1 that peaks the mode at its amplitude, Q15 of full. */")
    print("#define DRIVESND_MODES %du" % len(MODES))
    print("static const struct { int32_t c1, c2, strike; } drivesnd_modes[DRIVESND_MODES] = {")
    tot = sum(a for _, _, a in MODES)
    for f, tau, a in MODES:
        c1, c2, s = resonator(f, tau)
        strike = int(round(a / tot * s * 32768))
        print("    { %6d, %6d, %5d },   /* %5d Hz, %.1f ms */" % (q14(c1), q14(c2), strike, f, tau))
    print("};")
    r = math.exp(-math.pi * (HUMP_F / HUMP_Q) / FS)
    w = 2 * math.pi * HUMP_F / FS
    # Unit-RMS out for unit-RMS white in: the band pass's noise gain.
    c1, c2 = 2 * r * math.cos(w), r * r
    al = 1 - math.exp(-2 * math.pi * HUMP_LP / FS)
    y1 = y2 = x1 = lp = 0.0
    import random
    random.seed(1)
    acc = 0.0
    n = 200000
    for i in range(n):
        x = random.uniform(-1, 1) * math.sqrt(3)
        y = c1 * y1 - c2 * y2 + x - HUMP_ZERO * x1
        y2, y1, x1 = y1, y, x
        lp += (y - lp) * al
        acc += lp * lp
    gain = math.sqrt(acc / n)
    print()
    print("/* The noise's hump, %.0f Hz at Q %.1f: c1, c2 in Q14; the zero and the" % (HUMP_F, HUMP_Q))
    print(" * low pass's step at %.0f Hz, Q15; and the input's scale, Q15, that" % HUMP_LP)
    print(" * leaves white noise's RMS as it was. */")
    print("#define DRIVESND_HUMP_C1 %d" % q14(c1))
    print("#define DRIVESND_HUMP_C2 %d" % q14(c2))
    print("#define DRIVESND_HUMP_ZERO %d" % int(round(HUMP_ZERO * 32768)))
    print("#define DRIVESND_HUMP_LP %d" % int(round(al * 32768)))
    print("#define DRIVESND_HUMP_IN %d" % int(round(32768 / gain)))
    print()
    print("/* The tones: a phase step a sample, of 2^32 a cycle, and an RMS as a")
    print(" * fraction of the noise's, Q15. */")
    print("#define DRIVESND_TONES %du" % len(TONES))
    print("static const struct { uint32_t step; int32_t level; } drivesnd_tones[DRIVESND_TONES] = {")
    for f, rms in TONES:
        print("    { %10du, %5d },   /* %.0f Hz */" % (int(round(f / FS * 2**32)),
                                                      int(round(rms / 440.0 * 32768)), f))
    print("};")
    print()
    print("/* A quarter of a sine, 65 points, Q15. */")
    print("static const int16_t drivesnd_sine_q[65] = {")
    pts = [int(round(32767 * math.sin(math.pi / 2 * i / 64))) for i in range(65)]
    for i in range(0, 65, 9):
        print("    " + ", ".join("%5d" % v for v in pts[i:i + 9]) + ",")
    print("};")
    print()
    print("#endif /* PICO_COCO_DRIVESND_COEFFS_H */")


if __name__ == "__main__":
    main()
